-- Миграция: id группы, от имени которой оставлен комментарий.
-- Раньше "коммент от группы" (флаг 0b10000000) выводил группу из контента
-- (клуб поста/топика), поэтому работал только под контентом самой группы.
-- Эта колонка хранит выбранную группу, позволяя комментировать от её имени
-- под любым контентом. NULL - обычный коммент или старый коммент-от-группы
-- под контентом самой группы (обратная совместимость сохранена в getOwner()).
ALTER TABLE `comments` ADD COLUMN IF NOT EXISTS `club` bigint(20) DEFAULT NULL;
